use base64::Engine;

fn main() {
    println!("cargo:rerun-if-changed=../components/download-manifest.json");
    let output=std::process::Command::new(if cfg!(windows){"node.exe"}else{"node"})
        .args(["../scripts/export-build-assets.cjs","--component-manifest"]).output().expect("Cannot export component manifest");
    assert!(output.status.success(),"Cannot read component manifest: {}",String::from_utf8_lossy(&output.stderr));
    let manifest:serde_json::Value=serde_json::from_slice(&output.stdout).expect("Invalid component manifest");
    let destination=std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("Missing build output")).join("component-manifest.json");
    std::fs::write(destination,serde_json::to_vec(&manifest).expect("Invalid component manifest")).expect("Cannot prepare component manifest");
    // Fail before embedding unreadable generated assets. In some Windows
    // transparent-encryption setups Node and the Rust packager see different
    // bytes for the same file. Export and verify dist before embedding it.
    let dist = std::path::Path::new("../dist");
    println!("cargo:rerun-if-changed=../dist");
    println!("cargo:rerun-if-changed=../scripts/export-build-assets.cjs");
    if dist.join("index.html").exists() {
        if cfg!(windows) {
            prepare_windows_assets(dist);
        }
        let html = std::fs::read_to_string(dist.join("index.html"))
            .expect("Frontend assets are not readable UTF-8; run npm run build first");
        assert!(html.to_ascii_lowercase().starts_with("<!doctype html>"),
            "Frontend HTML is unreadable; run npm run build before desktop compilation");
        verify_text_assets(dist);
    }
    tauri_build::build()
}

fn prepare_windows_assets(dist: &std::path::Path) {
    // Node exports generated bytes through stdout. Rust writes and verifies its
    // own readable build inputs without changing system encryption settings.
    let output = std::process::Command::new("node.exe")
        .arg("../scripts/export-build-assets.cjs").output()
        .expect("Cannot start Node to prepare frontend assets");
    assert!(output.status.success(), "Cannot export frontend assets: {}",
        String::from_utf8_lossy(&output.stderr));
    let assets: serde_json::Value = serde_json::from_slice(&output.stdout)
        .expect("Invalid generated asset export");
    let root = dist.canonicalize().expect("Cannot resolve dist");
    let entries = assets.as_array().expect("Invalid asset list");
    for asset in entries {
        let relative = std::path::Path::new(asset["path"].as_str().expect("Missing asset path"));
        assert!(!relative.as_os_str().is_empty() && relative.components().all(|c|
            matches!(c, std::path::Component::Normal(_))), "Invalid generated asset path");
        let destination = root.join(relative);
        assert!(destination.parent().expect("Missing asset parent").canonicalize()
            .expect("Cannot resolve asset parent").starts_with(&root), "Asset escapes dist");
        let bytes = base64::engine::general_purpose::STANDARD
            .decode(asset["data"].as_str().expect("Missing asset data"))
            .expect("Invalid generated asset data");
        std::fs::write(&destination, &bytes).expect("Cannot prepare generated asset");
        assert_eq!(std::fs::read(&destination).expect("Cannot verify generated asset"), bytes,
            "Generated assets remain unreadable by Rust");
    }
    println!("cargo:warning=Verified {} frontend assets for desktop embedding", entries.len());
}

fn verify_text_assets(directory: &std::path::Path) {
    for entry in std::fs::read_dir(directory).expect("Cannot inspect frontend assets") {
        let entry = entry.expect("Cannot inspect frontend asset");
        let kind = entry.file_type().expect("Cannot inspect frontend asset type");
        assert!(!kind.is_symlink(), "Frontend assets must not contain symbolic links");
        let path = entry.path();
        if kind.is_dir() {
            verify_text_assets(&path);
        } else if matches!(path.extension().and_then(|s| s.to_str()), Some("html" | "js" | "css")) {
            let bytes = std::fs::read(&path).expect("Cannot read frontend asset");
            assert!(std::str::from_utf8(&bytes).is_ok() && !bytes.contains(&0),
                "Frontend asset is unreadable: {}; run npm run build", path.display());
        }
    }
}
