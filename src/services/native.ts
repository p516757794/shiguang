import { invoke, convertFileSrc } from '@tauri-apps/api/core';
import type { Bootstrap, ClipRecord, Settings, CaptureMode, ConversionJob, CaptureSession, PinData, ComponentDownload } from '../types';

export const imageUrl = (path: string | null) => path ? convertFileSrc(path) : '';
export const native = {
  bootstrap: () => invoke<Bootstrap>('bootstrap'),
  records: () => invoke<ClipRecord[]>('list_records'),
  storage: () => invoke<number>('storage_usage'),
  clearImages: () => invoke('clear_images'),
  favorite: (id: string, favorite: boolean) => invoke('favorite_record', { id, favorite }),
  remove: (ids: string[], view: string) => invoke('delete_records', { ids, view }),
  reorder: (ids: string[]) => invoke('reorder_records', { ids }),
  edit: (id: string | null, text: string, html: string | null, phrase: boolean, name: string | null = null) => invoke('save_record', { id, text, html, phrase, name }),
  paste: (id: string, formatted: boolean) => invoke('paste_record', { id, formatted }),
  copy: (id: string, formatted: boolean) => invoke('copy_record', { id, formatted }),
  copyText: (text: string) => invoke('copy_text', { text }),
  settings: (settings: Settings) => invoke('save_settings', { settings }),
  componentStatus: () => invoke<ComponentDownload>('component_status'),
  downloadComponents: () => invoke('download_components'),
  cancelComponentDownload: () => invoke('cancel_component_download'),
  capture: (mode: CaptureMode) => invoke('start_capture', { mode }),
  captureSession: () => invoke<CaptureSession>('capture_session'),
  captureReady: (imagePath: string) => invoke('capture_ready', { imagePath }),
  finishCapture: (selection: { x: number; y: number; width: number; height: number }) => invoke('finish_capture', { selection }),
  cancelCapture: () => invoke('cancel_capture'),
  pin: (id: string) => invoke('open_pin', { id }),
  pinData: () => invoke<PinData>('pin_data'),
  pinReady: () => invoke('pin_ready'),
  copyPin: () => invoke('copy_pin'),
  ocrPin: () => invoke<string>('recognize_pin'),
  foldPin: (folded: boolean) => invoke('fold_pin', { folded }),
  resizePin: (width: number, textHeight: number) => invoke('resize_pin', { width, textHeight }),
  closePin: () => invoke('close_pin'),
  ocr: (id: string) => invoke<string>('recognize_record', { id }),
  queue: (paths: string[]) => invoke('queue_conversion', { paths }),
  jobs: () => invoke<ConversionJob[]>('list_jobs'),
  controlJob: (id: string, action: string) => invoke('control_conversion', { id, action }),
  removeJobs: (ids: string[]) => invoke('delete_conversion_records', { ids }),
  exit: () => invoke('exit_application'),
};
